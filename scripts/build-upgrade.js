// Builds supabase/upgrade_all.sql: every migration in supabase/migrations, in
// order, in one file, so an existing database of any age can be brought up to
// date with a single paste into the SQL Editor. Every migration is safe to run
// more than once, so the ones a database already has are no-ops.
//
//   node scripts/build-upgrade.js     (run after adding or changing a migration)
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'supabase', 'migrations');
const files = fs.readdirSync(dir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
const first = files[0].slice(0, 4);
const last = files[files.length - 1].slice(0, 4);

let out = `-- NiblGo: bring an existing database fully up to date (migrations ${first} to ${last}).
--
-- GENERATED by scripts/build-upgrade.js from supabase/migrations/. Don't edit
-- it here; edit the migration and rebuild.
--
-- Paste the whole file into the Supabase SQL Editor and run it once. It works
-- on a database of any age: every migration is safe to run again, so the ones
-- you already ran do nothing and the ones you missed are applied, in order.
-- It runs as one transaction: if anything fails, nothing changes, and the
-- error names the step. Afterwards, run verify.sql.
--
-- A fresh project doesn't need this: schema.sql already includes everything.

begin;
`;
for (const f of files) {
  const sql = fs.readFileSync(path.join(dir, f), 'utf8').trimEnd();
  out += `\n-- ${'='.repeat(70)}\n-- ${f}\n-- ${'='.repeat(70)}\n\n${sql}\n`;
}
out += '\ncommit;\n';
fs.writeFileSync(path.join(__dirname, '..', 'supabase', 'upgrade_all.sql'), out);
console.log(`supabase/upgrade_all.sql: ${files.length} migrations (${first}-${last}), ${Math.round(out.length / 1024)} KB`);
